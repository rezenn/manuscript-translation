"""
step5b_extract_from_pdf_sheet.py
=================================
Extracts handwritten character crops from SCANNED or PHOTOGRAPHED
versions of the character sheet generated by create_character_sheet.py.

Because we generated the sheet ourselves, we know the EXACT geometry —
no grid detection needed. Coordinates are computed directly from the
same constants used in create_character_sheet.py.

SHEET LAYOUT (from create_character_sheet.py):
  GRID_COLS   = 5        columns of character groups
  REF_SIZE    = 80 px    reference box (shaded, left of each group)
  WRITE_BOXES = 5        empty boxes the writer fills in
  BOX_SIZE    = 70 px    each writing box
  ROW_HEIGHT  = 130 px   full row height including label
  COL_WIDTH   = 485 px   REF_SIZE + 5*(BOX_SIZE+5) + 30
  PADDING     = 20 px    outer margin
  TITLE_H     = 60 px    title area at top

INPUT:
  - PDF or image file of a filled-in sheet
  - Scanned flat: use as-is
  - Photographed: deskew is applied automatically

OUTPUT:
  - PNG crops saved to output_dir/<class_name>/hw_<style>_<writer>_NNNN.png
  - Same format as synthetic data in dataset_raw/
  - Optional light augmentation (rotation + brightness)

USAGE:
  python step5b_extract_from_pdf_sheet.py

Edit the JOBS list at the bottom to point to your files.
"""

