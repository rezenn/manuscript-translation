def print_summary():
    sources = {
        "Handwritten Noto"    : "dataset_raw/handwritten_noto",
        "Handwritten Ranjana" : "dataset_raw/handwritten_ranjana",
    }
    print("\n" + "="*60)
    print("DATASET SUMMARY")
    print("="*60)
    grand = 0
    for label, path in sources.items():
        if not os.path.exists(path):
            print(f"  {label:<26}: (not created yet)"); continue
        classes = [c for c in os.listdir(path)
                   if os.path.isdir(os.path.join(path, c))]
        if not classes:
            print(f"  {label:<26}: (empty)"); continue
        total = sum(
            len([f for f in os.listdir(os.path.join(path, c))
                 if f.endswith(".png")])
            for c in classes)
        avg   = total // len(classes) if classes else 0
        grand += total
        print(f"  {label:<26}: {total:5d} images "
              f"({len(classes)} classes, avg {avg}/class)")
    print(f"  {'TOTAL':<26}: {grand}")
    print("="*60)


