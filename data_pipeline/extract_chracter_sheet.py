# ═══════════════════════════════════════════════════════════════
# SHEET GEOMETRY — must match create_character_sheet.py exactly
# ═══════════════════════════════════════════════════════════════

GRID_COLS   = 5
WRITE_BOXES = 5
REF_SIZE    = 80
BOX_SIZE    = 70
ROW_HEIGHT  = 130
COL_WIDTH   = REF_SIZE + (WRITE_BOXES * (BOX_SIZE + 5)) + 30   # 485
PADDING     = 20
TITLE_H     = 60

# These are the ORIGINAL PIL pixel values from create_character_sheet.py.
# When a sheet is scanned or photographed, we apply a homography to warp
# it back to these canonical pixel coordinates before cropping.

CANONICAL_W = GRID_COLS * COL_WIDTH + 2 * PADDING   # 2465
# Height depends on how many characters are on the sheet

# Output settings
IMG_SIZE     = 128    # final crop size
# Blank detection: after resizing to 128x128, count pixels darker than INK_THRESH.
# Empty boxes have ~30 dark pixels (border + box number label bleed).
# Filled boxes have hundreds or thousands.
INK_THRESH   = 80    # pixel value below which we count as "ink"
BLANK_THRESH = 80    # fewer than this many ink pixels → treat cell as blank

# Augmentation
AUGMENT      = True
AUG_ROTATIONS  = [-5, -2, 2, 5]
AUG_BRIGHTNESS = [0.88, 1.12]

DEBUG_DIR = "debug_crops"


